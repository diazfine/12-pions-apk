export function getLocalizedCountryName(
  code: string,
  fallbackName: string,
  lang: string
): string {
  const upper = code.toUpperCase();
  if (lang === 'AR' && COUNTRY_NAMES_AR[upper]) {
    return COUNTRY_NAMES_AR[upper];
  }
  if (lang === 'EN' && COUNTRY_NAMES_EN[upper]) {
    return COUNTRY_NAMES_EN[upper];
  }
  return fallbackName;
}
